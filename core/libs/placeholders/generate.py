"""FEAT-GTS-261: writes a placeholder library's C source and module definition from its export list.

  python generate.py <list.nids> <output.c> <output.def>

Each line of the list is "<library> <NID>": a function GT Sport or GT7 imports that RyGTS does not implement.
The library exports one function per NID that reports "[stub] <library> <NID>" on its first call and
returns 0. A library with an empty list exports only ryty_stub_none: the game loads it at start but
calls nothing in it. See README.md.

FEAT-GTS-291: one build serves both games, so a line may end in "gt7=<value>": under GT7 that function
returns <value> (a 32-bit hex or decimal number) instead of 0. The game is told apart as the runtime
does (core/libs/GameSerial.hpp): SHADGT_GAME=gt7 or gts/gtsport, else GT7.exe is GT7.
"""
import re
import sys
from pathlib import Path

ENTRY = re.compile(r'^(lib[A-Za-z0-9_\-]+) ([A-Za-z0-9+\-]{11})(?: gt7=(0x[0-9A-Fa-f]{1,8}|[0-9]+))?$')

# The running game, read once: SHADGT_GAME as the launcher sets it, else the executable's name.
GAME_CHECK = r'''static volatile LONG game_known; /* 0: not read yet, 1: GT Sport, 2: GT7 */
static int running_gt7(void) {
    LONG known = game_known;
    if (known == 0) {
        char game[16];
        DWORD length = GetEnvironmentVariableA("SHADGT_GAME", game, sizeof(game));
        int gt7 = 0, set = 0;
        if (length > 0 && length < sizeof(game)) {
            if (lstrcmpiA(game, "gt7") == 0) { gt7 = 1; set = 1; }
            else if (lstrcmpiA(game, "gts") == 0 || lstrcmpiA(game, "gtsport") == 0) set = 1;
        }
        if (!set) {
            wchar_t path[MAX_PATH * 2];
            DWORD size = GetModuleFileNameW(NULL, path, MAX_PATH * 2);
            if (size > 0 && size < MAX_PATH * 2) {
                const wchar_t* name = path;
                for (const wchar_t* c = path; *c; ++c) if (*c == L'\\' || *c == L'/') name = c + 1;
                gt7 = lstrcmpiW(name, L"GT7.exe") == 0;
            }
        }
        known = gt7 ? 2 : 1;
        InterlockedExchange(&game_known, known);
    }
    return known == 2;
}'''


def main(listing, source, definition):
    library = Path(listing).stem
    entries = []
    for number, line in enumerate(Path(listing).read_text(encoding='ascii').splitlines(), 1):
        match = ENTRY.match(line)
        if not match:
            sys.exit(f'{listing}:{number}: expected "<library> <NID>" or "<library> <NID> gt7=<value>"')
        owner, nid, gt7 = match.groups()
        value = int(gt7, 0) if gt7 is not None else None
        if value is not None and value > 0xFFFFFFFF:
            sys.exit(f'{listing}:{number}: gt7= is a 32-bit value')
        entries.append((owner, nid, value))
    nids = [nid for _, nid, _ in entries]
    if len(set(nids)) != len(nids):
        sys.exit(f'{listing}: a NID is listed twice')
    lines = ['/* Generated by core/libs/placeholders/generate.py from ' + library + '.nids; do not edit. */',
             '#include <stdint.h>', '#include <stdio.h>', '#include <windows.h>', '']
    if entries:
        lines.append(f'static volatile LONG seen[{len(entries)}];')
        lines.append('static const char* const names[] = {' +
                     ','.join('"' + owner + ' ' + nid + '"' for owner, nid, _ in entries) + '};')
        lines.append('static void note(int i) { if (!InterlockedExchange(&seen[i], 1)) { fputs("[stub] ", stderr); '
                     'fputs(names[i], stderr); fputc(10, stderr); fflush(stderr); } }')
        if any(value is not None for _, _, value in entries):
            lines.append(GAME_CHECK)
        for i, (_, _, value) in enumerate(entries):
            result = '(int32_t)0' if value is None else f'running_gt7() ? (int32_t)0x{value:X}u : (int32_t)0'
            lines.append(f'__attribute__((sysv_abi)) int64_t s{i}(void) {{ note({i}); return {result}; }}')
    else:
        lines.append('__attribute__((sysv_abi)) int64_t ryty_stub_none(void) { return 0; }')
    Path(source).write_text('\n'.join(lines) + '\n', encoding='ascii', newline='\n')
    exports = [f'  "{nid}"=s{i}' for i, (_, nid, _) in enumerate(entries)] or ['  ryty_stub_none']
    Path(definition).write_text('\n'.join([f'LIBRARY {library}.prx', 'EXPORTS'] + exports) + '\n',
                                encoding='ascii', newline='\n')


if __name__ == '__main__':
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    main(*sys.argv[1:])
